#!/usr/bin/env python3
"""
Prints SQL that fills a DEV Supabase project with fake players, so previews
have someone to match with: 200 players with IGNs, friend codes, in-game
icons, votes on every candy line (some lines popular, some not), Top 3s and
friendships. Paste the output into the dev project's SQL editor after the
migrations (scripts/bundle-migrations.sh).

    python3 scripts/dev_seed.py > /tmp/dev_seed.sql

It refuses to run on a database with more than 10 real accounts, so it can't
land on production by mistake. Running it again replaces the fake players.

It also adds two helpers for testing with your own dev account (run them in
the SQL editor; YOUR_IGN is the IGN you set in Profile on the preview):

    select public.dev_befriend('YOUR_IGN', 15);    -- 15 fake friends
    select public.dev_requests_to('YOUR_IGN', 3);  -- 3 fake friend requests to you
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LINES = [line["id"] for line in json.loads((ROOT / "src" / "data" / "candy-lines.json").read_text())]
AVATARS = list(json.loads((ROOT / "src" / "data" / "avatars.json").read_text()))
PLAYERS = 200
PREFIX = "de000000-0000-4000-8000-"


def array(values: list[str]) -> str:
    return "array[" + ",".join("'" + v.replace("'", "''") + "'" for v in values) + "]::text[]"


SQL = f"""-- Dev seed: {PLAYERS} fake players (generated by scripts/dev_seed.py). DEV PROJECT ONLY.
do $$
begin
  if (select count(*) from auth.users where id::text not like '{PREFIX}%') > 10 then
    raise exception 'This database has real players. The dev seed only runs on a dev project.';
  end if;
end
$$;

-- Start over: removing the auth users cascades to profiles, votes and friendships.
delete from auth.users where id::text like '{PREFIX}%';

insert into auth.users (id, raw_user_meta_data)
select ('{PREFIX}' || lpad(g::text, 12, '0'))::uuid, '{{}}'::jsonb
from generate_series(1, {PLAYERS}) g;

-- IGNs, friend codes, icons; most seen in the last few weeks, a few long gone.
update public.profiles pr set
  ign = 'Dev' || initcap((array['sleepy','dozy','snore','nappy','dreamy','cozy','drowsy','yawn'])[1 + (s.g % 8)]) || s.g,
  friend_code = '5' || lpad(s.g::text, 11, '0'),
  game_avatar = ({array(AVATARS)})[1 + (s.g * 7919) % {len(AVATARS)}] || ':normal',
  open_to_friends = s.g % 10 <> 0,
  last_seen_at = now() - case when s.g % 25 = 0 then interval '90 days' else random() * interval '20 days' end
from (select ('{PREFIX}' || lpad(g::text, 12, '0'))::uuid as id, g from generate_series(1, {PLAYERS}) g) s
where pr.id = s.id;

-- Votes on every line: each line gets its own popularity, each player leans a bit.
with lines as (
  select line_id, 0.05 + 0.6 * random() as want_p, 0.05 + 0.25 * random() as dont_p
  from unnest({array(LINES)}) as line_id
),
players as (
  select ('{PREFIX}' || lpad(g::text, 12, '0'))::uuid as id, 0.5 + random() as lean
  from generate_series(1, {PLAYERS}) g
),
rolls as (select p.id, l.line_id, l.want_p * p.lean as want_p, l.dont_p, random() as r from players p cross join lines l)
insert into public.preferences (user_id, line_id, choice)
select id, line_id,
  (case when r < want_p then 'want' when r < want_p + dont_p then 'dont_want' else 'undecided' end)::public.choice
from rolls;

-- Top 3: three of each player's wants.
update public.preferences p set top = true
from (
  select user_id, line_id, row_number() over (partition by user_id order by random()) as n
  from public.preferences
  where user_id::text like '{PREFIX}%' and choice = 'want'
) pick
where p.user_id = pick.user_id and p.line_id = pick.line_id and pick.n <= 3;

-- Friendships: about 15 each, both directions.
insert into public.friends (user_id, friend_id)
select both_ways.u, both_ways.f from (
  select ('{PREFIX}' || lpad(x::text, 12, '0'))::uuid as a, ('{PREFIX}' || lpad(y::text, 12, '0'))::uuid as b
  from generate_series(1, {PLAYERS}) x, generate_series(1, {PLAYERS}) y
  where x < y and random() < 0.075
) pairs
cross join lateral (values (pairs.a, pairs.b), (pairs.b, pairs.a)) as both_ways(u, f)
on conflict do nothing;

-- Helpers for your own dev account, found by the IGN you set in Profile.
create or replace function public.dev_player(who text)
returns uuid
language sql
stable
security definer
set search_path = ''
as $$
  select pr.id from public.profiles pr
  where pr.ign = who and pr.id::text not like '{PREFIX}%'
$$;

-- You and n fake players (with room on their lists) become friends.
create or replace function public.dev_befriend(who text, n int default 15)
returns int
language plpgsql
security definer
set search_path = ''
as $$
declare
  me uuid := public.dev_player(who);
  added int := 0;
  other uuid;
begin
  if me is null then raise exception 'No dev account with IGN %', who; end if;
  for other in
    select pr.id from public.profiles pr
    where pr.id::text like '{PREFIX}%'
      and not exists (select 1 from public.friends f where f.user_id = me and f.friend_id = pr.id)
      and (select count(*) from public.friends f where f.user_id = pr.id) < public.max_friends()
    order by random()
    limit n
  loop
    insert into public.friends (user_id, friend_id) values (me, other), (other, me) on conflict do nothing;
    added := added + 1;
  end loop;
  return added;
end
$$;

-- n fake players send you a friend request.
create or replace function public.dev_requests_to(who text, n int default 3)
returns int
language plpgsql
security definer
set search_path = ''
as $$
declare
  me uuid := public.dev_player(who);
  added int;
begin
  if me is null then raise exception 'No dev account with IGN %', who; end if;
  insert into public.friend_requests (from_id, to_id)
  select pr.id, me from public.profiles pr
  where pr.id::text like '{PREFIX}%'
    and not exists (select 1 from public.friends f where f.user_id = me and f.friend_id = pr.id)
  order by random()
  limit n
  on conflict (from_id, to_id) do update set status = 'open', created_at = now(), responded_at = null;
  get diagnostics added = row_count;
  return added;
end
$$;

revoke execute on function public.dev_player(text), public.dev_befriend(text, int), public.dev_requests_to(text, int)
  from public, anon, authenticated;
"""

if __name__ == "__main__":
    print(SQL)
